#!/usr/bin/env bash
# Generate hosts/<hostname>/ from the running machine.
#
# Monitors are only read inside a running Hyprland session. Everything else
# (keyboard layout, GPU vendor, laptop detection) is read from read-only
# system interfaces. Nothing outside the repo is written.
set -Eeuo pipefail

REPO_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=scripts/lib.sh
source "$REPO_DIR/scripts/lib.sh"

DRY_RUN=0
ASSUME_YES=0
while (($#)); do
  case "$1" in
    --dry-run) DRY_RUN=1 ;;
    -y|--yes) ASSUME_YES=1 ;;
    -h|--help)
      cat <<'EOF'
Usage: scripts/host.sh [--dry-run] [--yes]
Generates hosts/<hostname>/.config/hypr/host.lua and, on laptops,
hosts/<hostname>/.config/waybar/host.jsonc.
EOF
      exit 0
      ;;
    *) die "Unknown option: $1" ;;
  esac
  shift
done

HOST_NAME="$(current_hostname | tr -d '[:space:]')"
[[ "$HOST_NAME" =~ ^[A-Za-z0-9._-]+$ ]] || die "Unsafe hostname: $HOST_NAME"
DEST="$REPO_DIR/hosts/$HOST_NAME"
HYPR_FILE="$DEST/.config/hypr/host.lua"
WAYBAR_FILE="$DEST/.config/waybar/host.jsonc"

TMP_DIR="$(mktemp -d)"
trap 'rm -rf -- "$TMP_DIR"' EXIT

HYPR_CONTENT="$TMP_DIR/host.lua"
WAYBAR_CONTENT="$TMP_DIR/host.jsonc"
: > "$HYPR_CONTENT"

{
  printf '%s\n' "-- Generated by ./install.sh host for $HOST_NAME."
  printf '%s\n' "-- Machine-specific Hyprland overrides; loaded from ~/.config/hypr/hyprland.lua."
  printf '%s\n' "-- Re-run ./install.sh host inside Hyprland to refresh monitor rules."
  printf '\n'
} >> "$HYPR_CONTENT"

monitors_written=0
if have hyprctl && hyprctl monitors -j > "$TMP_DIR/monitors.json" 2>/dev/null; then
  if ! jq -e 'type == "array" and length > 0' "$TMP_DIR/monitors.json" >/dev/null 2>&1; then
    warn "hyprctl returned no monitor data; leaving the base auto rule in charge."
  else
    {
      printf '%s\n' "-- Monitors (from hyprctl monitors -j)."
      while IFS=$'\t' read -r name width height refresh x y scale; do
        [[ -n "$name" ]] || continue
        [[ "$width" =~ ^[0-9]+$ && "$height" =~ ^[0-9]+$ ]] || continue
        [[ "$name" =~ ^[A-Za-z0-9._-]+$ ]] || { warn "Skipping unsafe monitor name: $name"; continue; }
        [[ "$refresh" =~ ^[0-9]+([.][0-9]+)?$ ]] || refresh="60"
        [[ "$x" =~ ^-?[0-9]+$ && "$y" =~ ^-?[0-9]+$ ]] || continue
        [[ "$scale" =~ ^[0-9]+([.][0-9]+)?$ ]] || scale="1"
        printf 'hl.monitor({ output = "%s", mode = "%sx%s@%s", position = "%sx%s", scale = %s })\n' \
          "$name" "$width" "$height" "$refresh" "$x" "$y" "$scale"
      done < <(jq -r '.[] | [.name, .width, .height, .refreshRate, .x, .y, .scale] | @tsv' "$TMP_DIR/monitors.json")
      printf '\n'
    } >> "$HYPR_CONTENT"
    monitors_written=1
  fi
else
  {
    printf '%s\n' "-- No monitor rules generated: not inside a running Hyprland session."
    printf '%s\n' "-- The base catch-all rule will auto-detect monitors."
    printf '\n'
  } >> "$HYPR_CONTENT"
fi

layout=""
variant=""
if have localectl; then
  layout="$(localectl status 2>/dev/null | awk -F': ' '/X11 Layout/{print $2; exit}' || true)"
  variant="$(localectl status 2>/dev/null | awk -F': ' '/X11 Variant/{print $2; exit}' || true)"
  [[ -n "$layout" ]] || layout="$(localectl status 2>/dev/null | awk -F': ' '/VC Keymap/{print $2; exit}' || true)"
fi
if [[ -n "$layout" && "$layout" =~ ^[A-Za-z0-9_,+-]+$ ]]; then
  [[ "$variant" =~ ^[A-Za-z0-9_,+-]*$ ]] || variant=""
  {
    printf '%s\n' "-- Keyboard layout (from localectl status)."
    printf 'hl.config({ input = { kb_layout = "%s", kb_variant = "%s" } })\n' "$layout" "$variant"
    printf '\n'
  } >> "$HYPR_CONTENT"
else
  printf '%s\n' '-- Keyboard layout not generated: localectl returned no usable X11/VC layout.' >> "$HYPR_CONTENT"
  printf '\n' >> "$HYPR_CONTENT"
fi

mapfile -t vendors < <(
  for f in /sys/class/drm/card*/device/vendor; do
    [[ -r "$f" ]] && cat "$f"
  done | sort -u
)
has_nvidia=0
has_amd=0
has_intel=0
for v in "${vendors[@]}"; do
  case "$v" in
    0x10de) has_nvidia=1 ;;
    0x1002) has_amd=1 ;;
    0x8086) has_intel=1 ;;
  esac
done
vendor_summary=""
((has_amd)) && vendor_summary+="AMD "
((has_intel)) && vendor_summary+="Intel "
((has_nvidia)) && vendor_summary+="NVIDIA "
vendor_summary="${vendor_summary:-unknown}"
info "Detected GPU vendor(s): ${vendor_summary% }"
if (( has_nvidia )); then
  if (( ASSUME_YES )) || confirm "NVIDIA GPU detected. Write an NVIDIA environment block to the host file?"; then
    {
      printf '%s\n' "-- NVIDIA environment (written after confirmation)."
      printf '%s\n' 'hl.env("LIBVA_DRIVER_NAME", "nvidia")'
      printf '%s\n' 'hl.env("__GLX_VENDOR_LIBRARY_NAME", "nvidia")'
      printf '%s\n' 'hl.env("GBM_BACKEND", "nvidia-drm")'
      printf '%s\n' 'hl.env("NVD_BACKEND", "direct")'
      printf '\n'
    } >> "$HYPR_CONTENT"
  else
    printf '%s\n' '-- NVIDIA environment block not written (user declined).' >> "$HYPR_CONTENT"
    printf '\n' >> "$HYPR_CONTENT"
  fi
fi

is_laptop=0
if have hostnamectl; then
  chassis="$(hostnamectl chassis 2>/dev/null || true)"
  case "$chassis" in
    laptop|notebook|convertible|tablet) is_laptop=1 ;;
  esac
fi
if (( ! is_laptop )); then
  for b in /sys/class/power_supply/BAT*; do
    [[ -e "$b" ]] && { is_laptop=1; break; }
  done
fi

if (( is_laptop )); then
  {
    printf '%s\n' "-- Laptop touchpad defaults; edit to taste."
    printf '%s\n' 'hl.config({ input = { touchpad = { natural_scroll = true } } })'
    printf '\n'
  } >> "$HYPR_CONTENT"
  {
    printf '%s\n' '{'
    printf '%s\n' '  // Generated fragment for laptop-only Waybar modules.'
    printf '%s\n' '  // No output key: include this from your own Waybar config if you want it.'
    printf '%s\n' '  "battery": { "format": "{capacity}%" },'
    printf '%s\n' '  "backlight": { "format": "{percent}%" }'
    printf '%s\n' '}'
  } > "$WAYBAR_CONTENT"
else
  rm -f -- "$WAYBAR_CONTENT"
fi

write_checked() {
  local src="$1" dest="$2"
  if [[ -f "$dest" ]] && cmp -s -- "$src" "$dest"; then
    info "Unchanged: ${dest#"$REPO_DIR"/}"
    return 0
  fi
  if [[ -f "$dest" ]]; then
    diff -u -- "$dest" "$src" || true
    if ! (( ASSUME_YES )); then
      confirm "Overwrite ${dest#"$REPO_DIR"/}?" || { warn "Kept existing ${dest#"$REPO_DIR"/}."; return 0; }
    fi
  fi
  if (( DRY_RUN )); then
    info "[dry-run] would write ${dest#"$REPO_DIR"/}"
    return 0
  fi
  mkdir -p -- "$(dirname -- "$dest")"
  cp -- "$src" "$dest"
  info "Wrote ${dest#"$REPO_DIR"/}"
}

write_checked "$HYPR_CONTENT" "$HYPR_FILE"
if (( is_laptop )); then
  write_checked "$WAYBAR_CONTENT" "$WAYBAR_FILE"
fi

if (( monitors_written == 0 )); then
  info "No monitor rules were generated. Run ./install.sh host inside Hyprland to capture them."
fi
info "Review and commit hosts/$HOST_NAME/ when it looks right."
